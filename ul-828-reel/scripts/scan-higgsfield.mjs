#!/usr/bin/env node
// Scans public/higgsfield/ for generated stills (img-*.png|jpg) and B-roll
// (clip-*.mp4), reads their dimensions, and writes src/higgsfield.ts so the
// shot plan can reference what actually exists. A clip that has not been
// generated yet simply is not listed, and the shot plan falls back to a still.
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";

const DIR = "public/higgsfield";
const FFMPEG = process.env.FFMPEG || "ffmpeg";
mkdirSync(DIR, { recursive: true });
mkdirSync(path.join(DIR, "bg"), { recursive: true });

const meta = (p) => {
  let s = "";
  try { execFileSync(FFMPEG, ["-hide_banner", "-i", p], { stdio: ["ignore", "pipe", "pipe"] }); }
  catch (e) { s = (e.stderr || "").toString(); }
  const m = s.match(/Stream #0:\d+.*?: Video: .*?, (\d+)x(\d+)/);
  const d = s.match(/Duration: (\d+):(\d+):(\d+\.\d+)/);
  const fr = s.match(/(\d+(?:\.\d+)?) fps/);
  return m ? { w: +m[1], h: +m[2], dur: d ? (+d[1]) * 3600 + (+d[2]) * 60 + (+d[3]) : 0, fps: fr ? +fr[1] : 0 } : null;
};

const files = readdirSync(DIR).filter((f) => /^(img|clip)-.*\.(png|jpg|mp4)$/i.test(f)).sort();
const stills = [], clips = [];
for (const f of files) {
  const p = path.join(DIR, f);
  const m = meta(p);
  if (!m) { console.warn("unreadable:", f); continue; }
  const id = f.replace(/^(img|clip)-\d+-/, "").replace(/\.(png|jpg|mp4)$/i, "");
  if (/\.mp4$/i.test(f)) {
    clips.push({ id, file: f, w: m.w, h: m.h, ar: +(m.w / m.h).toFixed(3), seconds: +m.dur.toFixed(2), fps: m.fps });
  } else {
    const bg = path.join(DIR, "bg", f.replace(/\.(png|jpg)$/i, ".jpg"));
    // Wash grade baked in (see prep-assets.mjs) — no CSS filter at render time.
    if (!existsSync(bg)) execFileSync("python3", ["scripts/plate.py", p, bg, "0.6", "0.30"]);
    stills.push({ id, file: f, bg: "bg/" + path.basename(bg), w: m.w, h: m.h, ar: +(m.w / m.h).toFixed(3) });
  }
}
const ts = `// AUTO-GENERATED by scripts/scan-higgsfield.mjs — do not edit by hand.
// Generated with Higgsfield (Nano Banana Pro stills from the real product
// photography as references; Kling 3.0 image-to-video B-roll from those stills).

export type HfStill = { id: string; file: string; bg: string; w: number; h: number; ar: number };
export type HfClip = { id: string; file: string; w: number; h: number; ar: number; seconds: number; fps: number };

export const HF_STILLS: HfStill[] = ${JSON.stringify(stills, null, 1)};
export const HF_CLIPS: HfClip[] = ${JSON.stringify(clips, null, 1)};

/** A still by id; portrait variants carry the same id with a "-9x16" suffix. */
export const still = (id: string): HfStill | undefined => HF_STILLS.find((s) => s.id === id);
export const clip = (id: string): HfClip | undefined => HF_CLIPS.find((c) => c.id === id);
`;
writeFileSync("src/higgsfield.ts", ts);
console.log(`${stills.length} stills, ${clips.length} clips`);
for (const s of stills) console.log(`  still ${s.id.padEnd(22)} ${s.w}x${s.h}`);
for (const c of clips) console.log(`  clip  ${c.id.padEnd(22)} ${c.w}x${c.h} ${c.seconds}s`);
